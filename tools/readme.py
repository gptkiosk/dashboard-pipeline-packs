#!/usr/bin/env python3
"""Write the catalog of approved templates and tools into README.md, from the same files the release index is built from.

The catalog sits between the catalog markers in README.md. --check fails when README.md differs from what this script
would write, so the README and the dashboard's store list cannot disagree.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build  # noqa: E402

START, END = "<!-- catalog:start (generated by tools/readme.py; do not edit by hand) -->", "<!-- catalog:end -->"
KIND_TITLES = {"agents": "Agents", "system_tools": "System tools", "providers": "Providers", "checks": "Dashboard checks", "services": "Services"}


def cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def catalog(packs: Path, platform: dict) -> str:
    out = ["## Approved templates", ""]
    folders = sorted(p for p in packs.iterdir() if p.is_dir() and not p.name.startswith(".")) if packs.is_dir() else []
    if not folders:
        out += ["None yet.", ""]
    for folder in folders:
        files, _ = build.pack_files(folder)
        manifest = json.loads(files["pack.json"])
        trust = "Official" if manifest.get("author") in platform["maintainers"] else "Community"
        for type_id in manifest.get("project_types", []):
            t = json.loads(files[f"project-types/{type_id}.json"])
            out += [f"### {t['label']}", "",
                    f"`{type_id}` in pack `{manifest['id']}` {manifest['pack_version']} · {trust}, by {manifest.get('author', 'unknown')} · "
                    f"dashboard {manifest['app_min']} or newer", "", cell(t["summary"]), ""]
            settings = [f["label"] for f in t.get("customize", [])]
            if settings:
                out += ["Settings you choose: " + ", ".join(settings) + ".", ""]
            needs = build.requirements(manifest, files)
            if needs:
                # A template's agents are alternatives: any one installed is enough.
                out += ["Needs: " + "; ".join(f"one of the agents {', '.join(v)}" if k == "agents" else f"{KIND_TITLES[k].lower()} {', '.join(v)}"
                                              for k, v in needs.items()) + ".", ""]
    out += ["## Approved tools", "", "A template may require only these. Asking for a new one is its own pull request to `platform/tools.json`.", ""]
    for kind, title in KIND_TITLES.items():
        out += [f"### {title}", "", "| Name | Id | Since | What it does |", "|---|---|---|---|"]
        out += [f"| {cell(t['name'])} | `{t['id']}` | {t['app_min']} | {cell(t['description'])} |" for t in platform[kind]]
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def render(readme: str, packs: Path, platform: dict) -> str:
    if START not in readme or END not in readme:
        raise SystemExit("README.md has no catalog markers")
    head, rest = readme.split(START, 1)
    return head + START + "\n\n" + catalog(packs, platform) + "\n" + END + rest.split(END, 1)[1]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if README.md is out of date; write nothing")
    args = parser.parse_args(argv)
    path = build.ROOT / "README.md"
    current = path.read_text("utf-8")
    wanted = render(current, build.ROOT / "packs", build.load_platform())
    if args.check:
        if current != wanted:
            print("README.md is out of date: run python3 tools/readme.py and commit the result.", file=sys.stderr)
            return 1
        print("README.md catalog is current.")
        return 0
    path.write_text(wanted, "utf-8")
    print("README.md catalog written.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
